// Token Radar — the value model and the farm plans.
//
// The board ranks pre-token protocols by an implied value that comes only from the
// sealed snapshot's own figures. No protocol name is ever special-cased: the same
// function scores every row, and the same plan builder writes every farm plan.
//
// Model "early-value-1":
//
//   base      = tvl_usd x 0.30            — a token, if issued, is priced off the
//                                           capital the protocol already holds.
//   growth    = clamp(change_7d, -50, 150)  (per cent; unreported counts as 0)
//   growthF   = 1 + growth/100 x 0.75    — a protocol gaining TVL fast is worth
//                                           more than one bleeding it; the clamp
//                                           keeps one wild week from dominating.
//   maturity  = 0.65 + 0.35 x sqrt(min(age_days, 1825) / 1825)
//                                         — age in days since DefiLlama first
//                                           tracked it; the square root rewards
//                                           survival early and flattens after
//                                           five years. Unknown age counts as 180.
//   breadth   = 1 + 0.04 x min(chains - 1, 5)
//                                         — each extra chain the protocol runs on
//                                           adds 4%, capped at +20%: wider reach,
//                                           wider future holder base.
//   implied   = max(1, round(base x growthF x maturity x breadth))
//
// The board is the snapshot's watchlist (the floor, never the ceiling) plus the
// highest-TVL pre-token protocols below the floor, by TVL, up to 160 of them.
// Protocols whose token already trades are set aside: the dashboard shows them in
// a separate "Already trading" list at their market's own value, never mixed into
// the ranked board.

/** One protocol entry of the sealed snapshot: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, stated in the dashboard and in the README. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_step: number;
  breadth_max_extra: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.75,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.65,
  maturity_range: 0.35,
  maturity_days: 1825,
  unknown_age_days: 180,
  breadth_step: 0.04,
  breadth_max_extra: 5,
};

/** The model's version label, shown in the dashboard and the README. */
export const MODEL_VERSION = 'early-value-1';

/** How many pre-token protocols below the watchlist floor the early radar carries. */
export const EARLY_ROWS = 160;

/** How many already-trading protocols the dashboard's live list carries. */
export const LIVE_ROWS = 24;

